"use strict";
const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const v2Bytes = fs.readFileSync(path.join(root, "preview-v2.html"));
assert.equal(crypto.createHash("sha256").update(v2Bytes).digest("hex"), "3a8262c92d71a302d555bb25343de5ca58966d6f48f91f29f35dbfcbea2d9bfa", "preserved V2 changed");
const html = read("preview-v3.html");
const production = read("index.html");
const css = read("assets/preview-v3.css");
const js = read("assets/preview-v3.js");
assert(html.includes("Знания, которые <em>можно доказать.</em>"));
assert(html.includes("Профессиональная проверка навыков начинающих специалистов в финансах. Получи объективный результат, профиль компетенций и место в рейтинге."));
assert(html.includes("What I cannot create, I do not understand."));
assert(html.includes("Знать недостаточно. <strong>Важно уметь применить.</strong>"));
assert(html.includes('name="robots" content="noindex, nofollow, noarchive"'));
assert(html.includes('href="preview-v2.html"'));
assert(production.includes('<title>SkillCheck — знания, которые можно доказать</title>'));
assert(production.includes('property="og:image" content="social-preview.png"'));
assert(production.includes('href="assets/preview-v3.css"'));
assert(production.includes('src="assets/preview-v3.js"'));
assert(!production.includes('name="robots" content="noindex'));
assert(!production.includes('preview-v2.html'));
assert(!production.includes('дизайн-превью'));
assert(production.includes('href="ranking.html"'));
for (const id of ["fa-junior", "ca-junior", "fpa-junior", "acc-junior", "bi-junior"]) assert(html.includes('href="test.html?test=' + id + '"'));
for (const id of ["fa-junior", "ca-junior", "fpa-junior", "acc-junior", "bi-junior", "tourism-junior", "software-junior", "product-project-junior"]) assert(production.includes('href="test.html?test=' + id + '"'));
assert.match(css, /backdrop-filter:blur/);
assert.match(css, /--parallax-x/);
assert.match(css, /--tilt-x/);
assert.match(css, /prefers-reduced-motion:reduce/);
assert.match(js, /pointermove/);
assert.match(js, /IntersectionObserver/);
assert(!["fetch(", "XMLHttpRequest", "WebSocket", "localStorage", "sessionStorage"].some(token => js.includes(token)));
assert(fs.statSync(path.join(root, "preview-v3.html")).size < 50000);
assert(fs.statSync(path.join(root, "assets", "preview-v3.css")).size < 50000);
assert(fs.statSync(path.join(root, "assets", "preview-v3.js")).size < 15000);
console.log("V3 production and preview checks passed: preserved V2, approved copy, restrained effects, eight production roles and no network/storage side effects.");
